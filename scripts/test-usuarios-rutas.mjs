import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';
const bundle=await build({entryPoints:['src/config/usuariosPermisos.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const {catalogoPermisos,puedeAbrirRuta,inicioUsuario}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const sql=readFileSync('supabase/migrations/20261110120000_usuarios_permisos_generales.sql','utf8');
const catalogoServidor=JSON.parse(sql.match(/SELECT '(\{"clientes"[^\n]+})'::jsonb/)[1]);
assert.deepEqual(catalogoPermisos,catalogoServidor,'El formulario no ofrece permisos que el backend desconozca');
const base={admin:false,configurado:true,activo:true,solo_restaurante:false,nombre:'Persona',perfil:'personalizado',permisos:{}};
const lector={...base,permisos:{clientes:['consultar']}};
for(const path of ['/clientes/nuevo','/clientes/registro/editar','/ventas','/usuarios','/usuarios/nuevo','/comercio','/afip'])assert.equal(puedeAbrirRuta(lector,path),false,path);
assert.equal(puedeAbrirRuta(lector,'/clientes'),true);
assert.equal(puedeAbrirRuta(lector,'/seguridad'),true);
assert.equal(puedeAbrirRuta(lector,'/listados/clientes'),true);
assert.equal(puedeAbrirRuta(lector,'/listados/proveedores'),false);
assert.equal(puedeAbrirRuta({...lector,activo:false},'/clientes'),false);
assert.equal(puedeAbrirRuta({...base,configurado:false},'/ventas'),true,'Compatibilidad con acceso existente');
assert.equal(puedeAbrirRuta({...base,configurado:false},'/usuarios'),false,'Gestión de usuarios exclusiva de administración');
assert.equal(puedeAbrirRuta({...base,admin:true},'/usuarios'),true);
const chofer={...base,permisos:{transporte:['consultar','operar']}};
for(const path of ['/transporte/resumen','/transporte/servicios'])assert.equal(puedeAbrirRuta(chofer,path),true);
for(const path of ['/transporte/servicios/nuevo','/transporte/choferes','/transporte/tarifas','/transporte/liquidacion','/caja'])assert.equal(puedeAbrirRuta(chofer,path),false);
const coordinador={...base,permisos:{transporte:['consultar','crear','editar','operar','administrar']}};
assert.equal(puedeAbrirRuta(coordinador,'/transporte/servicios/nuevo'),true);
assert.equal(puedeAbrirRuta(coordinador,'/transporte/liquidacion'),false);
assert.equal(inicioUsuario(chofer,{transporte:true}),'/transporte/resumen');
assert.equal(inicioUsuario({...base,permisos:{campo:['consultar']}},{campo:true}),'/campo/establecimientos');
assert.equal(inicioUsuario(base,{}),'/sin-acceso');
console.log('OK catálogo frontend/backend, perfiles y rutas de consulta, alta, edición, usuarios y Transporte.');
