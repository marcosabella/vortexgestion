// Resolver real con Supabase simulado. No se conecta a ARCA ni a servicios remotos.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source=readFileSync('supabase/functions/_shared/emisor-fiscal.ts','utf8');
const exports={};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports});
const resolver=exports.resolverConfiguracionFiscal;
const issuer={id:'issuer-1',comercio_id:'tenant',activo:true,predeterminado:true,cuit_emisor:'20111111112',punto_venta:2,ambiente:'homologacion',certificado_key:'test-key'};
const legacy={comercio_id:'tenant',activo:true,cuit_emisor:'20333333334',punto_venta:1,ambiente:'homologacion'};
let multi=true,active=true;
const tables=[];
const db={from(table){tables.push(table);let filters=[];const q={select(){return q},eq(field,value){filters.push([field,value]);return q},async maybeSingle(){const rows=table==='comercio_parametrizacion'?[{comercio_id:'tenant',parametros:{funciones:{multiples_cuit:multi}}}]:table==='emisores_fiscales'?[{...issuer,activo:active}]:[legacy];return {data:rows.find(row=>filters.every(([field,value])=>row[field]===value))||null,error:null}}};return q}};
const snapshot={cuit_emisor:issuer.cuit_emisor,punto_venta:issuer.punto_venta,ambiente:issuer.ambiente};
assert.equal((await resolver(db,'tenant',{emisorId:issuer.id,snapshot,ventaLegacy:false})).certificado_key,'test-key');
await assert.rejects(resolver(db,'foreign',{emisorId:issuer.id,snapshot,ventaLegacy:false}),/no pertenece/);
await assert.rejects(resolver(db,'tenant',{emisorId:issuer.id,snapshot:{...snapshot,punto_venta:1},ventaLegacy:false}),/no coincide/);
await assert.rejects(resolver(db,'tenant',{emisorId:issuer.id,ventaLegacy:false}),/identidad fiscal/);
tables.length=0;active=false;
await assert.rejects(resolver(db,'tenant',{emisorId:issuer.id,snapshot,ventaLegacy:false}),/no está activo/);
assert.ok(!tables.includes('afip_config'),'No usa otras credenciales si el emisor falla');
active=true;
await assert.rejects(resolver(db,'tenant'),/Seleccione el emisor/);
assert.equal((await resolver(db,'tenant',{permitirPredeterminado:true})).id,issuer.id);
assert.equal((await resolver(db,'tenant',{ventaLegacy:true})).cuit_emisor,legacy.cuit_emisor);
multi=false;
assert.equal((await resolver(db,'tenant')).cuit_emisor,legacy.cuit_emisor);
assert.equal((await resolver(db,'tenant',{emisorId:issuer.id,snapshot,ventaLegacy:false})).cuit_emisor,issuer.cuit_emisor);
console.log('OK selección fiscal: credenciales exactas, tenant, emisor activo, identidad de venta, sin fallback y compatibilidad legacy. Sin solicitudes de CAE.');
