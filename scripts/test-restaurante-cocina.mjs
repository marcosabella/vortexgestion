// Pruebas locales con datos ficticios: estados mixtos, aislamiento y controles.
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Module from 'node:module';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bundle = await build({ stdin: { contents: `export * from './src/utils/restauranteCocina'; export {RestauranteCocina} from './src/components/restaurante/RestauranteCocina';`, resolveDir: repo, loader: 'tsx' }, write: false, bundle: true, platform: 'node', format: 'cjs', jsx: 'automatic', external: ['react', 'react-dom', 'react/jsx-runtime'], plugins: [{ name: 'print-fixture', setup(b) { b.onResolve({ filter: /^\.\/RestauranteImpresion$/ }, () => ({ path: 'print', namespace: 'fixture' })); b.onLoad({ filter: /.*/, namespace: 'fixture' }, () => ({ contents: 'export const RestauranteImpresion=()=>null;', loader: 'js' })); } }] });
const compiled = new Module(path.join(repo, 'scripts', '.cocina-test.cjs'));
compiled.filename = path.join(repo, 'scripts', '.cocina-test.cjs');
compiled.paths = Module._nodeModulePaths(path.join(repo, 'scripts'));
compiled._compile(bundle.outputFiles[0].text, compiled.filename);
const { cocinaEtapa, cocinaPaso, cocinaTablero, cocinaMinutos, RestauranteCocina } = compiled.exports;
const now = Date.parse('2026-10-09T15:20:00Z');
const item = (id, estado, comanda_id = 'c1', sector_id = 's1') => ({ id, estado, comanda_id, sector_id, pedido_id: 'p1', descripcion: `Plato ${id}`, cantidad: 2, adicionales: [{ nombre: 'Queso', precio: 50 }], observaciones: 'Sin sal' });
const pedido = { id: 'p1', numero: 12, modalidad: 'mesa', estado: 'en_atencion', cuenta: 'abierta', version: 5, prioridad: false, observaciones: 'Alergia a maní', cliente_nombre: 'Dato privado', direccion: 'Dirección privada', telefono: '555-privado', total: 98765, created_at: '2026-10-09T15:00:00Z' };
const comanda = { id: 'c1', numero: 21, pedido_id: 'p1', sector_id: 's1', aviso_cancelacion: false, created_at: '2026-10-09T15:10:00Z' };
const data = { admin: false, usuario_id: 'u1', permisos: ['cocina'], sector_id: 's1', pedidos: [pedido], comandas: [comanda, { ...comanda, id: 'c2', numero: 22, sector_id: 's2' }], items: [item('i1', 'pendiente'), item('i2', 'lista'), item('i3', 'pendiente', 'c2', 's2')], sectores: [{ id: 's1', nombre: 'Cocina' }, { id: 's2', nombre: 'Barra' }], mesas: [{ id: 'm1', nombre: 'Mesa 4' }], cuenta_mesas: [{ pedido_id: 'p1', mesa_id: 'm1', activa: true }], eventos: [] };

assert.equal(cocinaEtapa([item('1', 'pendiente'), item('2', 'preparacion')]), 'recibidas');
assert.equal(cocinaEtapa([item('1', 'aceptada'), item('2', 'lista')]), 'preparacion');
assert.equal(cocinaEtapa([item('1', 'preparacion'), item('2', 'cancelada')]), 'preparacion');
assert.equal(cocinaEtapa([item('1', 'lista'), item('2', 'entregada'), item('3', 'cancelada')]), 'listas');
assert.equal(cocinaEtapa([item('1', 'entregada'), item('2', 'cancelada')]), 'finalizadas');
assert.equal(cocinaPaso('pendiente'), 'aceptar');
assert.equal(cocinaPaso('aceptada'), 'preparar');
assert.equal(cocinaPaso('preparacion'), 'listo');
assert.equal(cocinaPaso('lista'), undefined);
assert.equal(cocinaPaso('cancelada'), undefined);
assert.equal(cocinaMinutos(comanda.created_at, now), 10);
assert.equal(cocinaMinutos('invalid', now), null);
assert.equal(cocinaMinutos('2026-10-09T15:30:00Z', now), 0);
assert.deepEqual(cocinaTablero(data).map(t => t.comanda.id), ['c1']);
assert.equal(cocinaTablero(data, 's2').length, 0, 'Cambiar filtro no habilita otro sector');
assert.equal(cocinaTablero(data)[0].destino, 'Mesa 4');

const query = { trabajando: false, error: null, errorOperacion: null, pendientes: [], isFetching: false, dataUpdatedAt: now, operar: async () => null, refetch: async () => {}, reintentar: async () => {} };
const render = (state = data, overrides = {}, online = true) => renderToStaticMarkup(React.createElement(RestauranteCocina, { data: state, query: { ...query, ...overrides }, ahora: now, online, comercioNombre: 'Prueba' }));
const html = render();
assert.match(html, /Mesa 4|Alergia a maní|Sin sal|Queso|10 min/);
assert.doesNotMatch(html, /Dato privado|Dirección privada|555-privado|98765|Plato i3/);
assert.match(html, /Aceptar pendientes/);
for (const [estado, accion] of [['pendiente', 'Aceptar pendientes'], ['aceptada', 'Preparar aceptados'], ['preparacion', 'Marcar en preparación como listos']]) {
  const state = structuredClone(data); state.items[0].estado = estado;
  assert.match(render(state), new RegExp(accion));
  const blocked = render(state, {}, false);
  const button = blocked.match(new RegExp(`<button[^>]*>${accion}[\\s\\S]*?</button>`))?.[0];
  assert.ok(button?.includes('disabled'), 'Sin conexión se bloquea: ' + accion);
}
const cancel = structuredClone(data);
cancel.pedidos[0].estado = 'cancelado'; cancel.items[0].estado = 'cancelada'; cancel.items[1].estado = 'cancelada'; cancel.comandas[0].aviso_cancelacion = true;
assert.equal(cocinaTablero(cancel).length, 1, 'Aviso visible aunque no queden productos activos');
assert.match(render(cancel), /Cancelaciones por confirmar|Confirmar aviso recibido/);
assert.doesNotMatch(render(cancel), /Aceptar pendientes|Preparar aceptados|Marcar en preparación como listos/);
cancel.comandas[0].aviso_cancelacion = false;
assert.equal(cocinaTablero(cancel).length, 0);
const served = structuredClone(data); served.items[0].estado = 'entregada'; served.items[1].estado = 'entregada';
assert.equal(cocinaTablero(served).length, 0, 'Entregadas salen del tablero');
const rounds = structuredClone(data); rounds.comandas.push({ ...comanda, id: 'c3', numero: 23, created_at: '2026-10-09T15:15:00Z' }); rounds.items.push(item('i4', 'pendiente', 'c3'));
assert.deepEqual(cocinaTablero(rounds).map(t => t.comanda.numero), [21, 23], 'Las nuevas rondas no se mezclan');
const priority = structuredClone(rounds); priority.pedidos.push({ ...pedido, id: 'p2', prioridad: true }); priority.comandas[2].pedido_id = 'p2'; priority.items[3].pedido_id = 'p2';
assert.equal(cocinaTablero(priority)[0].pedido.id, 'p2');
console.log('OK cocina: estados mixtos, sector, rondas, prioridad, tiempos, cancelaciones, entrega y controles sin conexión');
const parcial = structuredClone(data);
parcial.pedidos.push({ ...pedido, id: 'p3', numero: 13 });
parcial.comandas.push({ ...comanda, id: 'c3', numero: 23, pedido_id: 'p3' });
parcial.items.push({ ...item('i4', 'pendiente', 'c3'), pedido_id: 'p3' });
const bloqueadoParcial = render(parcial, { pendientes: [{ clave: 'intento', accion: 'preparar', datos: { pedido_id: 'p1', version: 5 } }] });
const comandaBloqueada = bloqueadoParcial.match(/<article aria-label="Comanda 21"[\s\S]*?<\/article>/)?.[0];
const comandaLibre = bloqueadoParcial.match(/<article aria-label="Comanda 23"[\s\S]*?<\/article>/)?.[0];
const botones = html => [...html.matchAll(/<button\b[^>]*>[\s\S]*?<\/button>/g)].map(m => m[0]).filter(b => b.includes('Aceptar'));
const deshabilitado = b => /^<button[^>]*\sdisabled(?:=|\s|>)/.test(b);
assert.ok(botones(comandaBloqueada).length > 0 && botones(comandaBloqueada).every(deshabilitado));
assert.ok(botones(comandaLibre).some(b => !deshabilitado(b)));
assert.match(bloqueadoParcial, /Pedido #12|Comprobar operación: preparar|15 segundos/);
console.log('OK cocina: el intento pendiente bloquea su pedido, no las comandas de otros pedidos');
