// SQL real en PostgreSQL temporal local, sin Supabase ni Mercado Pago.
import assert from 'node:assert/strict';
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, realpathSync, rmSync } from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
const root = realpathSync(os.tmpdir()), cluster = mkdtempSync(path.join(root, 'vortex-reembolso-sql-')), data = path.join(cluster, 'data');
const pgBin = process.env.PG_BIN || 'C:/Program Files/PostgreSQL/17/bin';
const listener = net.createServer(); await new Promise(r => listener.listen(0, '127.0.0.1', r)); const port = listener.address().port; await new Promise(r => listener.close(r));
const env = { ...process.env, PGCLIENTENCODING: 'UTF8' };
const command = (name, args, input) => {
  const r = spawnSync(path.join(pgBin, name + '.exe'), args, { input, encoding: 'utf8', windowsHide: true, env, stdio: name === 'pg_ctl' ? 'ignore' : 'pipe', timeout: 30000 });
  if (r.error) throw r.error; if (r.status) throw Error(r.stderr || r.stdout); return (r.stdout || '').trim();
};
const pgArgs = ['-X', '-qAt', '-h', '127.0.0.1', '-p', String(port), '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'];
const sql = input => command('psql', pgArgs, input);
const asyncSql = input => new Promise((resolve, reject) => {
  const p = spawn(path.join(pgBin, 'psql.exe'), pgArgs, { env, windowsHide: true }); let out = '', err = '';
  p.stdout.on('data', x => out += x); p.stderr.on('data', x => err += x); p.once('error', reject); p.once('close', code => code ? reject(Error(err)) : resolve(out.trim())); p.stdin.end(input);
});
const id = n => `10000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
const c1 = id(1), c2 = id(2), admin = id(3), operator = id(4), outsider = id(5);
const actor = (role = 'service_role', user = admin) => `SET request.jwt.claim.role='${role}';SET request.jwt.claim.sub='${user}';SET ROLE ${role};`;
const prepare = (n, user = admin, commerce = c1) => `SELECT preparar_reembolso_pedido_online('${id(n)}','${commerce}','${user}');`;
const job = n => JSON.parse(sql(actor() + prepare(n)));
const fail = (query, message) => assert.throws(() => sql(query), message);
const createOrder = (n, commerce = c1, state = 'recibido', paid = true) => sql(`INSERT INTO pedidos_online(id,comercio_id,estado,estado_pago,importe_pagado,venta_id) VALUES('${id(n)}','${commerce}','${state}',${paid ? "'aprobado',100" : "'no_iniciado',0"},NULL);
  INSERT INTO pedido_online_items VALUES(gen_random_uuid(),'${id(n)}','${id(90)}',NULL,2);
  ${paid ? `INSERT INTO mercadopago_operaciones(id,comercio_id,pedido_online_id,modalidad,payment_id,external_reference,importe,estado,approved_at) VALUES('${id(n + 100)}','${commerce}','${id(n)}','checkout_pro','${n}','pedido-${n}',100,'aprobado',now());` : ''}`);
let started = false;
try {
  command('initdb', ['-D', data, '-U', 'postgres', '-A', 'trust', '--encoding=UTF8', '--no-locale']);
  command('pg_ctl', ['-D', data, '-l', path.join(cluster, 'postgres.log'), '-o', `-h 127.0.0.1 -p ${port}`, '-w', 'start']); started = true;
  sql(`CREATE ROLE authenticated;CREATE ROLE anon;CREATE ROLE service_role BYPASSRLS;CREATE SCHEMA auth;
    CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$SELECT current_setting('request.jwt.claim.role',true)$$;
    CREATE TABLE comercio(id uuid PRIMARY KEY);
    CREATE TABLE comercio_usuarios(comercio_id uuid REFERENCES comercio(id),user_id uuid REFERENCES auth.users(id),activo boolean,rol text,solo_restaurante boolean);
    CREATE FUNCTION user_belongs_to_comercio(p uuid) RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=public AS $$SELECT EXISTS(SELECT 1 FROM comercio_usuarios WHERE comercio_id=p AND user_id=auth.uid() AND activo AND NOT solo_restaurante)$$;
    CREATE TABLE pedidos_online(id uuid PRIMARY KEY,comercio_id uuid REFERENCES comercio(id),estado text,estado_pago text,importe_pagado numeric,venta_id uuid,total numeric DEFAULT 0);
    CREATE TABLE productos(id uuid PRIMARY KEY,comercio_id uuid REFERENCES comercio(id),stock integer);
    CREATE TABLE producto_variantes(id uuid PRIMARY KEY,producto_id uuid REFERENCES productos(id),stock integer);
    CREATE TABLE pedido_online_items(id uuid PRIMARY KEY,pedido_id uuid REFERENCES pedidos_online(id),producto_id uuid REFERENCES productos(id),producto_variante_id uuid REFERENCES producto_variantes(id),cantidad integer);
    CREATE TABLE mercadopago_operaciones(id uuid PRIMARY KEY,comercio_id uuid REFERENCES comercio(id),pedido_online_id uuid REFERENCES pedidos_online(id),venta_id uuid,pago_venta_id uuid,modalidad text,payment_id text,external_reference text,importe numeric,estado text,approved_at timestamptz,importe_reembolsado numeric NOT NULL DEFAULT 0,medio_pago text,cuotas integer,raw_response jsonb);
    INSERT INTO comercio VALUES('${c1}'),('${c2}');INSERT INTO auth.users VALUES('${admin}'),('${operator}'),('${outsider}');
    INSERT INTO comercio_usuarios VALUES('${c1}','${admin}',true,'admin',false),('${c1}','${operator}',true,'operador',false),('${c2}','${outsider}',true,'admin',false);
    INSERT INTO productos VALUES('${id(90)}','${c1}',7),('${id(91)}','${c2}',50);
    INSERT INTO producto_variantes VALUES('${id(92)}','${id(90)}',3);
    GRANT USAGE ON SCHEMA public,auth TO authenticated,anon,service_role;`);
  sql(readFileSync('supabase/migrations/20261104120000_reembolso_cancelacion_pedido_online.sql', 'utf8'));
  sql(readFileSync('supabase/migrations/20261104123000_corregir_importe_reembolso_online.sql', 'utf8'));
  sql('GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;');
  createOrder(10);
  sql(`INSERT INTO pedido_online_items VALUES(gen_random_uuid(),'${id(10)}','${id(90)}','${id(92)}',2);`);
  fail(actor('authenticated') + prepare(10), /permission denied/);
  fail(actor('anon') + prepare(10), /permission denied/);
  for (const user of [operator, outsider]) fail(actor() + prepare(10, user), /Solo un administrador/);
  fail(actor('authenticated') + `SELECT actualizar_estado_pedido_online('${id(10)}','cancelado');`, /debe cancelarse con la devolucion/);
  fail(actor() + prepare(10, admin, c2), /Solo un administrador/);
  const r = job(10);
  assert.equal(r.puede_procesar, true);
  assert.equal(sql(`SELECT estado FROM pedidos_online WHERE id='${id(10)}';`), 'cancelado');
  assert.equal(sql(`SELECT stock FROM productos WHERE id='${id(90)}';`), '9');
  assert.equal(sql(`SELECT stock FROM producto_variantes WHERE id='${id(92)}';`), '5');
  const concurrent = job(10);
  assert.equal(concurrent.puede_procesar, false);
  assert.equal(concurrent.idempotency_key, r.idempotency_key);
  assert.equal(sql(actor() + `SELECT fijar_importe_reembolso_online('${r.id}','${r.intento}',100);`), '100.00');
  assert.equal(sql(actor() + `SELECT fijar_importe_reembolso_online('${r.id}','${r.intento}',70);`), '100.00', 'El importe del POST no cambia entre reintentos');
  sql(actor() + `SELECT finalizar_intento_reembolso_online('${r.id}','${r.intento}','error','Timeout',NULL);`);
  const retry = job(10);
  assert.equal(retry.idempotency_key, r.idempotency_key);
  assert.notEqual(retry.intento, r.intento);
  sql(actor() + `SELECT finalizar_intento_reembolso_online('${r.id}','${r.intento}','error','Worker viejo',NULL);`);
  assert.equal(sql(`SELECT estado FROM pedido_online_reembolsos WHERE id='${r.id}';`), 'procesando');
  sql(actor() + `SELECT sincronizar_reembolso_pedido_online('${id(110)}','10',30);`);
  assert.equal(sql(`SELECT estado_pago FROM pedidos_online WHERE id='${id(10)}';`), 'parcialmente_reembolsado');
  sql(actor() + `SELECT sincronizar_reembolso_pedido_online('${id(110)}','10',100);SELECT finalizar_intento_reembolso_online('${r.id}','${retry.intento}','error','Respuesta tardia',NULL);`);
  assert.equal(sql(`SELECT estado FROM pedido_online_reembolsos WHERE id='${r.id}';`), 'completado');
  assert.equal(job(10).puede_procesar, false);
  sql(actor() + `SELECT sincronizar_reembolso_pedido_online('${id(110)}','10',30);SELECT registrar_pago_mercadopago_aprobado('${id(110)}','10','visa',1,'{}');`);
  assert.equal(sql(`SELECT estado_pago FROM pedidos_online WHERE id='${id(10)}';`), 'reembolsado');
  assert.equal(sql(`SELECT stock FROM productos WHERE id='${id(90)}';`), '9', 'Webhooks repetidos no descuentan stock otra vez');
  assert.equal(sql(`SELECT stock FROM producto_variantes WHERE id='${id(92)}';`), '5');
  fail(actor() + `SELECT sincronizar_reembolso_pedido_online('${id(110)}','otro-pago',100);`, /incompatible/);
  fail(actor() + `SELECT sincronizar_reembolso_pedido_online('${id(110)}','10',101);`, /incompatible/);
  assert.equal(sql(actor('authenticated', outsider) + 'SELECT count(*) FROM pedido_online_reembolsos;'), '0', 'RLS oculta otros comercios');
  assert.equal(sql(actor('authenticated') + 'SELECT count(*) FROM pedido_online_reembolsos;'), '1');
  fail(actor('authenticated') + 'DELETE FROM pedido_online_reembolsos;', /permission denied/);
  createOrder(11, c1, 'cancelado');
  job(11);
  assert.equal(sql(`SELECT stock FROM productos WHERE id='${id(90)}';`), '9', 'Pedido historico cancelado no repone stock de nuevo');
  createOrder(12, c1, 'recibido', false);
  sql(actor('authenticated') + `SELECT actualizar_estado_pedido_online('${id(12)}','cancelado');`);
  assert.equal(sql(`SELECT stock FROM productos WHERE id='${id(90)}';`), '9', 'Pedido sin pago no habia descontado stock');
  createOrder(13);
  sql(`UPDATE pedido_online_items SET producto_id='${id(91)}' WHERE pedido_id='${id(13)}';`);
  fail(actor() + prepare(13), /fuera del comercio/);
  assert.equal(sql(`SELECT estado FROM pedidos_online WHERE id='${id(13)}';`), 'recibido', 'Tenant invalido revierte toda la cancelacion');
  createOrder(14);
  sql(`INSERT INTO mercadopago_operaciones(id,comercio_id,pedido_online_id,modalidad,payment_id,importe,estado) VALUES('${id(214)}','${c1}','${id(14)}','checkout_pro','otro',100,'aprobado');`);
  fail(actor() + prepare(14), /unico pago/);
  createOrder(15);
  const racing = await Promise.all([asyncSql(actor() + prepare(15)), asyncSql(actor() + prepare(15))]);
  assert.equal(racing.map(JSON.parse).filter(value => value.puede_procesar).length, 1, 'Dos solicitudes concurrentes tienen un solo worker');
  createOrder(16, c2);
  fail(`INSERT INTO pedido_online_reembolsos(comercio_id,pedido_id,operacion_id,solicitado_por,importe) VALUES('${c1}','${id(16)}','${id(116)}','${admin}',100);`, /otro comercio/);
  console.log('OK PostgreSQL local: permisos admin, tenant y RLS, cancelacion y stock/variantes una vez, reintentos concurrentes, importe estable, webhook monotono, pedidos historicos, impagos y pagos ambiguos.');
} finally {
  if (started) command('pg_ctl', ['-D', data, '-m', 'immediate', '-w', 'stop']);
  const resolved = realpathSync(cluster);
  if (!resolved.startsWith(root + path.sep) || !path.basename(resolved).startsWith('vortex-reembolso-sql-')) throw Error('Ruta temporal no segura');
  rmSync(resolved, { recursive: true, force: true });
}
