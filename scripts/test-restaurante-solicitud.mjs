import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Module from 'node:module';
import { build } from 'esbuild';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bundle = await build({ stdin: { contents: `export * from './src/utils/restauranteSolicitud';`, resolveDir: repo, loader: 'ts' }, write: false, bundle: true, platform: 'node', format: 'cjs' });
const compiled = new Module(path.join(repo, 'scripts', '.solicitud-test.cjs'));
compiled.filename = path.join(repo, 'scripts', '.solicitud-test.cjs');
compiled._compile(bundle.outputFiles[0].text, compiled.filename);
const { restauranteSolicitud, restaurantePedidoIntento, restauranteCocinaIntentoResuelto } = compiled.exports;
let signal;
assert.equal(await restauranteSolicitud(s => { signal = s; return Promise.resolve('confirmada'); }, 30), 'confirmada');
assert.equal(signal.aborted, false);
await new Promise(resolve => setTimeout(resolve, 40));
assert.equal(signal.aborted, false, 'Cancelar el timer al recibir respuesta');
await assert.rejects(restauranteSolicitud(s => { signal = s; return new Promise(() => {}); }, 20), /no respondió a tiempo/);
assert.equal(signal.aborted, true, 'Abortar la solicitud que no responde, aunque su promesa ignore la cancelación');
const error = new Error('Error del servidor');
await assert.rejects(restauranteSolicitud(() => Promise.reject(error), 30), e => e === error);
assert.equal(restaurantePedidoIntento({ pedido_id: 'p1', version: 3 }), 'p1');
for (const datos of [null, [], 'p1', {}, { pedido_id: 3 }]) assert.equal(restaurantePedidoIntento(datos), null);
console.log('OK solicitudes: plazo máximo, cancelación, respuesta, error y pedido del intento');
const data = { pedidos: [{ id: 'p11', version: 5 }], items: [{ id: 'i11', pedido_id: 'p11', comanda_id: 'c11', estado: 'preparacion' }] };
const intento = { accion: 'preparar', datos: { pedido_id: 'p11', item_id: 'i11', comanda_id: 'c11', version: 4 } };
assert.equal(restauranteCocinaIntentoResuelto(data, intento), true, 'Pedido #11: preparación confirmada por estado y versión posterior');
assert.equal(restauranteCocinaIntentoResuelto(data, { ...intento, datos: { ...intento.datos, version: 5 } }), false);
assert.equal(restauranteCocinaIntentoResuelto(data, { ...intento, datos: { ...intento.datos, item_id: 'otro' } }), false);
assert.equal(restauranteCocinaIntentoResuelto(data, { ...intento, datos: { pedido_id: 'p11', version: 4 } }), false);
for (const accion of ['cobro', 'cerrar', 'rendir', 'entregar']) assert.equal(restauranteCocinaIntentoResuelto(data, { ...intento, accion }), false);
data.items[0].estado = 'aceptada'; assert.equal(restauranteCocinaIntentoResuelto(data, intento), false);
data.items[0].estado = 'lista'; assert.equal(restauranteCocinaIntentoResuelto(data, intento), true);
delete intento.datos.item_id;data.items.push({ id: 'i12', pedido_id: 'p11', comanda_id: 'c11', estado: 'aceptada' });
assert.equal(restauranteCocinaIntentoResuelto(data, intento), false, 'No resolver una comanda con preparación parcial');
data.items[1].estado = 'preparacion';assert.equal(restauranteCocinaIntentoResuelto(data, intento), true);
console.log('OK recuperación #11: avance confirmado, versión, producto/comanda, progreso parcial y pagos conservados');
